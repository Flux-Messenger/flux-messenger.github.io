// Helper to filter all stickers and emojis by search query
export function searchStickersAndEmojis(query: string): { stickers: StickerItem[]; emojis: { emoji: string; name: string }[] } {
  const q = query.toLowerCase().trim();
  if (!q) {
    return {
      stickers: STICKER_PACKS.flatMap(p => p.stickers),
      emojis: EMOJI_CATEGORIES.flatMap(c => c.emojis.slice(0, 15))
    };
  }

  const matchedStickers: StickerItem[] = [];
  STICKER_PACKS.forEach(pack => {
    pack.stickers.forEach(s => {
      if (s.name.toLowerCase().includes(q) || s.tags.some(t => t.toLowerCase().includes(q)) || (s.pack && s.pack.toLowerCase().includes(q))) {
        matchedStickers.push(s);
      }
    });
  });

  const matchedEmojis: { emoji: string; name: string }[] = [];
  EMOJI_CATEGORIES.forEach(cat => {
    cat.emojis.forEach(e => {
      if (e.name.toLowerCase().includes(q) || e.tags.some(t => t.toLowerCase().includes(q))) {
        matchedEmojis.push({ emoji: e.emoji, name: e.name });
      }
    });
  });

  return { stickers: matchedStickers, emojis: matchedEmojis };
}
